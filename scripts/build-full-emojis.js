// Regenerate src/emojis-full.js from Unicode's emoji-test.txt:
//   curl -sLO https://unicode.org/Public/emoji/latest/emoji-test.txt
//   node scripts/build-full-emojis.js emoji-test.txt
import { readFileSync, writeFileSync } from "node:fs";

const MAX = 255; // Jev's limit on choices per question
const SAMPLES = 8; // emojis shown in a category's description
const SKIN_TONE = /\u{1F3FB}|\u{1F3FC}|\u{1F3FD}|\u{1F3FE}|\u{1F3FF}/u;

const [source] = process.argv.slice(2);
if (!source) throw new Error("usage: node scripts/build-full-emojis.js emoji-test.txt");

const text = readFileSync(source, "utf8");
const version = text.match(/^# Version: (.+)$/m)?.[1] ?? "unknown";
const subgroups = new Map(); // "group|subgroup" → [[emoji, name]]
let group, subgroup;
for (const line of text.split("\n")) {
  if (line.startsWith("# group:")) group = line.slice(8).trim();
  else if (line.startsWith("# subgroup:")) subgroup = line.slice(11).trim();
  else if (line.includes("; fully-qualified") && group !== "Component") {
    const [, emoji, name] = line.match(/# (\S+) E\d+\.\d+ (.+)$/);
    if (SKIN_TONE.test(emoji)) continue;
    const key = `${group}|${subgroup}`;
    if (!subgroups.has(key)) subgroups.set(key, []);
    subgroups.get(key).push([emoji, name]);
  }
}

const categories = {};
for (const [key, entries] of subgroups) {
  const [group, subgroup] = key.split("|");
  const parts = Math.ceil(entries.length / MAX);
  if (parts > 1) entries.sort((a, b) => a[1].localeCompare(b[1])); // so each part spans a name range
  const size = Math.ceil(entries.length / parts);
  for (let p = 0; p < parts; p++) {
    const chunk = entries.slice(p * size, (p + 1) * size);
    const range = parts > 1 ? ` (${initial(chunk[0][1])}–${initial(chunk.at(-1)[1])})` : "";
    const id = parts > 1 ? `${subgroup}-${p + 1}` : subgroup;
    categories[id] = {
      description: `${group}: ${subgroup.replaceAll("-", " ")}${range}, e.g. ${chunk.slice(0, SAMPLES).map(([e]) => e).join(" ")}`,
      emojis: Object.fromEntries(chunk),
    };
  }
}

const count = Object.values(categories).reduce((n, c) => n + Object.keys(c.emojis).length, 0);
if (Object.keys(categories).length > MAX) throw new Error("Too many categories for one Jev question");

writeFileSync(new URL("../src/emojis-full.js", import.meta.url), `// Generated by scripts/build-full-emojis.js from Unicode emoji-test.txt ${version}. Do not edit.
// ${count} emojis without skin-tone variants, in ${Object.keys(categories).length} categories of at most ${MAX}.
export const FULL_EMOJIS = {
${Object.entries(categories).map(([id, c]) => `  ${JSON.stringify(id)}: ${JSON.stringify(c)},`).join("\n")}
};
`);
console.log(`Wrote ${count} emojis in ${Object.keys(categories).length} categories (Emoji ${version})`);

function initial(name) {
  return name.replace(/^flag: /, "")[0].toUpperCase();
}
